import { useMemo, type ReactNode } from 'react';
import type { TFunction } from 'i18next';
import { useTranslation } from 'react-i18next';
import type { Channels, ResponseOf } from '@rl/core';
import { useAiUi } from '../../lib/aiUi';
import { Markdown, type LinkHook } from '../../lib/markdown';
import { useReader } from '../../lib/reader';
import { safeText } from '../library/safeText';
import { formatTokens, formatUsd } from './format';
import { labelNamesPage, parseLabLink, type LabLink } from './labLinks';
import { useDocTitle, useProjectName } from './useLabels';
import './chat.css';

export type Turn = ResponseOf<Channels, 'chat:get'>['turns'][number] & { streaming?: boolean };
export type Card = Turn['cards'][number];

const short = (id: string) => id.slice(0, 8);

/** A `lab://` link as a button: it opens the reader (at the page), the note of a document, or a project. */
export function LabChip({ link, label }: { link: LabLink; label?: string }) {
  const { t } = useTranslation();
  const { openReader } = useReader();
  const { openProject } = useAiUi();
  const title = useDocTitle(link.kind === 'project' ? null : link.docId);
  const projectName = useProjectName(link.kind === 'project' ? link.id : null);
  const name = safeText(label?.trim() || title || projectName || (link.kind === 'project' ? short(link.id) : short(link.docId)));
  const text =
    link.kind === 'doc' ? (link.page && !labelNamesPage(name, link.page) ? t('chat.chipDocPage', { name, page: link.page }) : name) : link.kind === 'note' ? t('chat.chipNote', { name }) : t('chat.chipProject', { name });
  const open = () => {
    if (link.kind === 'doc') openReader(link.docId, link.page);
    else if (link.kind === 'note') openReader(link.docId, undefined, { panel: 'fileNote' });
    else openProject(link.id);
  };
  return (
    <button type="button" className="lab-chip" data-kind={link.kind} data-testid="lab-chip" title={t(`chat.chipOpen_${link.kind}`)} onClick={open}>
      {text}
    </button>
  );
}

/**
 * Link rule for text written by the model: only the three `lab://` forms become chips. Every other target, `http(s)`
 * included, is shown as text and never followed (nothing of model output navigates, opens a window or loads a page).
 */
export const modelLinkHook: LinkHook = (href, label, key) => {
  const link = parseLabLink(href);
  if (link) return <LabChip key={key} link={link} label={label} />;
  const target = /^(https?:\/\/)/i.test(href) ? ` (${href})` : '';
  return (
    <span key={key} className="plain-link" data-testid="plain-link">
      {safeText(label + target)}
    </span>
  );
};

/** A document by title, as a chip that opens the reader. */
export function DocChip({ docId }: { docId: string }) {
  return <LabChip link={{ kind: 'doc', docId }} />;
}

const MAX_CARD_DOCS = 5;

export function CardView({ card }: { card: Card }) {
  const { t } = useTranslation();
  return (
    <li className="chat-card" data-testid="chat-card" data-status={card.status}>
      <div className="chat-card-head">
        <span className="chat-card-name">{safeText(card.name)}</span>
        <span className={`badge chat-card-status-${card.status}`}>{t(`chat.card.${card.status}`)}</span>
      </div>
      <p className="chat-card-summary">{safeText(card.summary)}</p>
      {card.docIds.length > 0 && (
        <p className="chat-card-docs">
          {card.docIds.slice(0, MAX_CARD_DOCS).map((id) => (
            <DocChip key={id} docId={id} />
          ))}
          {card.docIds.length > MAX_CARD_DOCS && <span className="hint">{t('chat.card.more', { count: card.docIds.length - MAX_CARD_DOCS })}</span>}
        </p>
      )}
    </li>
  );
}

function errorText(code: string, t: TFunction): string {
  switch (code) {
    case 'CANCELLED':
      return t('chat.errors.cancelled');
    case 'AI_BUDGET_EXCEEDED':
      return t('chat.errors.cap');
    case 'no-access':
      return t('chat.errors.noAccess');
    case 'offline':
      return t('chat.errors.offline');
    default:
      return t('chat.errors.generic');
  }
}

function Usage({ usage }: { usage: NonNullable<Turn['usage']> }) {
  const { t } = useTranslation();
  return (
    <p className="chat-usage hint" data-testid="turn-usage">
      {t('chat.turnUsage', { input: formatTokens(usage.inputTokens), output: formatTokens(usage.outputTokens) })}
      {usage.usd !== null ? ` · ${formatUsd(usage.usd)}` : ''}
    </p>
  );
}

/** One turn: the user's text as written, or the answer, clearly marked as generated by the AI. */
export function TurnView({ turn, modelLabel }: { turn: Turn; modelLabel: string }) {
  const { t } = useTranslation();
  const body = useMemo<ReactNode>(
    () => (turn.role === 'assistant' ? <Markdown source={turn.text} className="chat-md" linkHook={modelLinkHook} /> : <p className="chat-user-text">{safeText(turn.text)}</p>),
    [turn.role, turn.text],
  );
  if (turn.role === 'user') {
    return (
      <li className="chat-turn user" data-testid="chat-turn-user">
        {body}
        {turn.contextDocIds.length > 0 && <p className="hint">{t('chat.withDocs', { count: turn.contextDocIds.length })}</p>}
      </li>
    );
  }
  return (
    <li className="chat-turn ai" data-testid="chat-turn-ai" aria-busy={turn.streaming || undefined}>
      <div className="ai-mark" data-testid="ai-mark">
        <span className="badge ai">{t('chat.generated')}</span>
        <span className="hint">{modelLabel}</span>
      </div>
      {body}
      {turn.streaming && turn.text === '' && <p className="hint" role="status">{t('chat.thinking')}</p>}
      {turn.cards.length > 0 && (
        <ul className="chat-cards" aria-label={t('chat.cards')}>
          {turn.cards.map((c) => (
            <CardView key={c.id} card={c} />
          ))}
        </ul>
      )}
      {turn.error && (
        <p className="chat-turn-error" role="alert" data-testid="turn-error" data-code={turn.error.code}>
          {errorText(turn.error.code, t)}
        </p>
      )}
      {turn.usage && <Usage usage={turn.usage} />}
    </li>
  );
}
